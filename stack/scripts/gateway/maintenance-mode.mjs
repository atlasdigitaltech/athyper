#!/usr/bin/env node
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const PRODUCTS = ["neon", "mesh", "admin"];
const scriptDir = dirname(fileURLToPath(import.meta.url));
const repositoryConfig = resolve(scriptDir, "../../config");

function usage(message) {
  if (message) console.error(`Error: ${message}\n`);
  console.error(`Usage:
  maintenance-mode enable <neon|mesh|admin|all> --start <ISO-8601> --end <ISO-8601> --reference <ID> [--status-url <URL>] [--config-root <path>]
  maintenance-mode disable <neon|mesh|admin|all> [--config-root <path>]
  maintenance-mode status [--config-root <path>]

Enabling maintenance takes effect immediately. Dates describe the displayed
window; use an external scheduler to run the enable command at a future time.`);
  process.exit(message ? 1 : 0);
}

function parseArguments(values) {
  const positionals = [];
  const options = {};
  const flags = new Set(["restart-gateway", "no-restart-gateway"]);
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (!value.startsWith("--")) { positionals.push(value); continue; }
    const name = value.slice(2);
    if (flags.has(name)) { options[name] = true; continue; }
    const optionValue = values[index + 1];
    if (!optionValue || optionValue.startsWith("--")) usage(`--${name} requires a value`);
    options[name] = optionValue;
    index += 1;
  }
  return { positionals, options };
}

function reloadGateway(configRoot, options) {
  const explicitRestart = options["restart-gateway"] === true;
  const windowsRuntime = process.platform === "win32" && !resolve(configRoot).startsWith(resolve(repositoryConfig));
  if (options["no-restart-gateway"] || (!explicitRestart && !windowsRuntime)) {
    console.log("Traefik file-provider hot reload requested.");
    return;
  }
  const container = process.env.ATHYPER_GATEWAY_CONTAINER || "athyper-gateway-1";
  console.log(`Restarting ${container} because Docker Desktop does not forward reliable bind-mount watch events...`);
  execFileSync("docker", ["restart", container], { stdio: "inherit" });
}

function defaultConfigRoot(explicit) {
  if (explicit) return resolve(explicit);
  if (process.env.ATHYPER_CONFIG) return resolve(process.env.ATHYPER_CONFIG);
  const windowsRuntime = "D:\\Stack\\athyper\\config";
  if (process.platform === "win32" && existsSync(windowsRuntime)) return windowsRuntime;
  return repositoryConfig;
}

function writeAtomic(path, content) {
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, content, "utf8");
  renameSync(temporary, path);
  // Docker Desktop bind mounts can miss a rename event even though the new
  // inode is visible in the container. Rewriting the already-complete target
  // emits the modify event Traefik's file provider needs for hot reload.
  writeFileSync(path, content, "utf8");
}

function loadState(path) {
  if (!existsSync(path)) return { applications: {} };
  try {
    const state = JSON.parse(readFileSync(path, "utf8"));
    return { applications: state.applications && typeof state.applications === "object" ? state.applications : {} };
  } catch (error) {
    throw new Error(`Cannot read ${path}: ${error.message}`);
  }
}

function yamlFor(applications) {
  const enabled = PRODUCTS.filter(product => applications[product]);
  if (!enabled.length) return null;
  const lines = ["# Generated by maintenance-mode. Do not edit while maintenance is active.", "http:", "  routers:"];
  for (const product of enabled) {
    const upper = product.toUpperCase();
    lines.push(
      `    ${product}-planned-maintenance:`,
      `      rule: 'Host(\`{{ env "APPS_ATHYPER_${upper}_HOST" }}\`)'`,
      "      entryPoints: [websecure]",
      "      service: athyper-maintenance-page@docker",
      "      priority: 10000",
      "      tls: {}"
    );
  }
  return `${lines.join("\n")}\n`;
}

function validatedDate(name, value) {
  if (!value) usage(`--${name} is required`);
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) usage(`--${name} must be an ISO-8601 date with timezone`);
  return date;
}

const { positionals, options } = parseArguments(process.argv.slice(2));
const [command, target] = positionals;
if (!command || !["enable", "disable", "status"].includes(command)) usage("unknown or missing command");
if ((command === "enable" || command === "disable") && ![...PRODUCTS, "all"].includes(target)) usage("a product or 'all' is required");

const configRoot = defaultConfigRoot(options["config-root"]);
const dynamicFile = join(configRoot, "gateway", "dynamic", "athyper.maintenance.yml");
const stateFile = join(configRoot, "gateway", "fallback", "maintenance-config.json");
if (!existsSync(dirname(dynamicFile)) || !existsSync(dirname(stateFile))) usage(`gateway configuration is missing under ${configRoot}`);

const state = loadState(stateFile);
if (command === "status") {
  console.log(JSON.stringify({ configRoot, applications: state.applications }, null, 2));
  process.exit(0);
}

const selected = target === "all" ? PRODUCTS : [target];
if (command === "enable") {
  const start = validatedDate("start", options.start);
  const end = validatedDate("end", options.end);
  if (end <= start) usage("--end must be later than --start");
  if (!options.reference) usage("--reference is required");
  if (options["status-url"]) {
    try { new URL(options["status-url"]); } catch { usage("--status-url must be an absolute URL"); }
  }
  for (const product of selected) {
    state.applications[product] = {
      reference: options.reference,
      startsAt: start.toISOString(),
      endsAt: end.toISOString(),
      ...(options["status-url"] ? { statusUrl: options["status-url"] } : {})
    };
  }
} else {
  for (const product of selected) delete state.applications[product];
}

writeAtomic(stateFile, `${JSON.stringify(state, null, 2)}\n`);
const dynamicConfiguration = yamlFor(state.applications);
if (dynamicConfiguration === null) {
  rmSync(dynamicFile, { force: true });
} else {
  writeAtomic(dynamicFile, dynamicConfiguration);
}
reloadGateway(configRoot, options);
console.log(`${command === "enable" ? "Enabled" : "Disabled"} maintenance for ${selected.join(", ")}.`);
console.log(`Traefik configuration: ${dynamicFile}`);
console.log(`Maintenance details: ${stateFile}`);
