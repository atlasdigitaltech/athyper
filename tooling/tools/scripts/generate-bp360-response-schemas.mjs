import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = process.cwd();
const sources = ['business-partner-360.ts', 'business-partner-360-sections.ts', 'business-partner-360-commercial-controls.ts'].map((file) => resolve(root, 'server/packages/contracts/master-data/src', file));
// Response contracts also reference browser workspace contracts with extensionless imports.
const program = ts.createProgram(sources, { strict: true, target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, skipLibCheck: true });
const checker = program.getTypeChecker();
const diagnostics = sources.flatMap((file) => [...program.getSyntacticDiagnostics(program.getSourceFile(file)), ...program.getSemanticDiagnostics(program.getSourceFile(file))]);
if (diagnostics.length) throw new Error(diagnostics.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')).join('\n'));
const types = ['BusinessPartner360Summary', 'BusinessPartner360Section', 'BusinessPartner360TaxRevealResult', 'BusinessPartner360BankRevealResult'];
const stable = (schemas) => schemas.sort((a, b) => JSON.stringify(a) < JSON.stringify(b) ? -1 : JSON.stringify(a) > JSON.stringify(b) ? 1 : 0);
function schema(type, stack = []) {
  if (type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown | ts.TypeFlags.TypeParameter)) return {};
  if (type.flags & ts.TypeFlags.StringLiteral) return { const: type.value, type: 'string' };
  if (type.flags & ts.TypeFlags.NumberLiteral) return { const: type.value, type: 'number' };
  if (type.flags & ts.TypeFlags.BooleanLiteral) return { const: type.intrinsicName === 'true', type: 'boolean' };
  if (type.flags & ts.TypeFlags.String) return { type: 'string' };
  if (type.flags & ts.TypeFlags.Number) return { type: 'number' };
  if (type.flags & ts.TypeFlags.Boolean) return { type: 'boolean' };
  if (type.flags & ts.TypeFlags.Null) return { type: 'null' };
  if (type.isUnion()) return { anyOf: stable(type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined)).map((t) => schema(t, stack))) };
  if (type.isIntersection()) return { allOf: stable(type.types.map((t) => schema(t, stack))) };
  if (stack.includes(type)) throw new Error(`Recursive type needs an explicit schema reference: ${checker.typeToString(type)}`);
  if (checker.isArrayType(type) || type.symbol?.name === 'ReadonlyArray') return { type: 'array', items: schema(checker.getTypeArguments(type)[0], [...stack, type]) };
  if (type.flags & ts.TypeFlags.Object) {
    const properties = {}, required = [];
    for (const property of checker.getPropertiesOfType(type)) {
      properties[property.name] = schema(checker.getTypeOfSymbolAtLocation(property, property.valueDeclaration ?? property.declarations[0]), [...stack, type]);
      if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name);
    }
    const index = checker.getIndexTypeOfType(type, ts.IndexKind.String);
    return { type: 'object', properties, ...(required.length ? { required } : {}), additionalProperties: index ? schema(index, [...stack, type]) : true };
  }
  throw new Error(`Unsupported response type: ${checker.typeToString(type)}`);
}
const output = {};
for (const name of types) {
  const symbol = sources.flatMap((file) => checker.getExportsOfModule(checker.getSymbolAtLocation(program.getSourceFile(file)))).find((symbol) => symbol.name === name);
  if (!symbol) throw new Error(`Missing response type ${name}`);
  output[name] = schema(checker.getDeclaredTypeOfSymbol(symbol));
}
const path = resolve(root, 'server/packages/services/master-data/src/business-partner-360-response-schemas.ts');
const content = '// Generated by pnpm openapi:bp360:generate from the shared response interfaces. Do not edit.\nexport const bp360ResponseSchemas = ' + JSON.stringify(output, null, 2) + ' as const;\n';
if (process.argv.includes('--write')) writeFileSync(path, content);
else if (readFileSync(path, 'utf8') !== content) throw new Error('BP360 response schemas are stale. Run pnpm openapi:bp360:generate.');
console.log('BP360 response schemas verified against shared TypeScript contracts.');
