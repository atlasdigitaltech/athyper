/** Build-time adapter: only reviewed sample content becomes static FreeMarker. */
import {
  getPlaneBrand,
  BRAND_PLANES,
} from "../../../packages/platform/foundation/brand/src/index";
import { WORKSPACES_BY_PLANE, IAM_PREVIEW_ACTS } from "../../../packages/platform/iam/identity-gate/src/workspace-showcase-data";
import {
  isLand,
  NODES,
  LINKS,
} from "../../../packages/platform/iam/identity-gate/src/workspace-map-data";

// Escape HTML and FreeMarker interpolation starts in canonical sample strings.
const escape = (value: string) =>
  value.replace(
    /[&<>"'$#]/g,
    (character) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
        $: "&#36;",
        "#": "&#35;",
      })[character]!,
  );
const xy = (lon: number, lat: number) => [(lon + 180) * 2, (85 - lat) * 2];
function mapSvg() {
  const dots: string[] = [];
  for (let lat = -55; lat <= 79; lat += 2) {
    for (let lon = -180; lon <= 180; lon += 2) {
      if (isLand(lon, lat)) {
        const [x, y] = xy(lon, lat);
        dots.push(`M${x},${y}h.01`);
      }
    }
  }
  const links = LINKS.map(([from, to]) => {
    const a = NODES.find((n) => n.id === from)!;
    const b = NODES.find((n) => n.id === to)!;
    const [x1, y1] = xy(a.lon, a.lat);
    const [x2, y2] = xy(b.lon, b.lat);
    return `<path class="kc-ws-route" d="M${x1},${y1} Q${(x1 + x2) / 2},${Math.min(y1, y2) - 35} ${x2},${y2}" />`;
  }).join("");
  return `<svg class="kc-ws-map" viewBox="0 0 720 300" role="img" aria-label="Illustrative partner network connecting global hubs"><g><path class="kc-ws-land-dots" d="${dots.join(" ")}" /></g><g>${links}</g>${NODES.map(
    (n) => {
      const [x, y] = xy(n.lon, n.lat);
      return `<circle class="kc-ws-node ${n.hub ? "kc-ws-hub" : "kc-ws-partner"}" cx="${x}" cy="${y}" r="${n.hub ? 4 : 2.5}"><title>${escape(n.name)}</title></circle>`;
    },
  ).join("")}</svg>`;
}
function slogan(text: string, atlas = false) {
  return `<svg class="${atlas ? "kc-ws-atlas-mark" : "kc-ws-slogan"}" viewBox="${atlas ? "375 415 260 75" : "0 440 1300 70"}" role="img" aria-label="${escape(text)}"><text x="${atlas ? "390.45" : "4"}" y="${atlas ? "471.23" : "495.28"}" font-size="50" font-weight="600" fill="currentColor">${escape(text)}</text></svg>`;
}
export function keycloakShowcaseFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const plane of BRAND_PLANES) {
    const w = WORKSPACES_BY_PLANE[plane][0];
    const brand = getPlaneBrand(plane);
    // A read-only preset conveys Atlas without suggesting a real operation ran.
    const acts = IAM_PREVIEW_ACTS[plane];
    const act = acts[0];
    let body = mapSvg();
    if (w.kind === "ledger") {
      const entries = w
        .ledger!.map(
          (entry) =>
            `<div class="kc-ws-entry"><p>${escape(entry.ref)} <span>${escape(entry.source)}</span></p>${entry.lines.map((line) => `<div class="kc-ws-ledger-row"><span>${escape(line.account)} · ${escape(line.label)}</span><span>${escape(line.debit ?? "—")}</span><span>${escape(line.credit ?? "—")}</span></div>`).join("")}</div>`,
        )
        .join("");
      body = `<div class="kc-ws-ledger-row kc-ws-columns"><span>Account</span><span>Debit</span><span>Credit</span></div><div class="kc-ws-ledger-window"><div class="kc-ws-tape"><div>${entries}</div><div aria-hidden="true">${entries}</div></div></div>`;
    } else if (w.kind === "chain") {
      body = `<ol class="kc-ws-chain">${w.chain!.map((step) => `<li><span class="kc-ws-step-dot" aria-hidden="true"></span><div><strong>${escape(step.name)}</strong><small>${escape(step.ref)} · ${escape(step.val)}</small></div><span class="kc-ws-state">${escape(step.state)}</span></li>`).join("")}</ol>`;
    }
    files[`_showcase-${plane}.ftl`] =
      `<#-- Generated by brand:sync:keycloak; edit shared workspace-showcase-data.ts. -->
<div class="kc-ws" data-showcase="${plane}">
  <section class="kc-ws-card" aria-label="${escape(w.tab)} sample workspace">
    <div class="kc-ws-title">${slogan(brand.description)}</div>
    <dl class="kc-ws-head">${w.head.map(([k, v]) => `<div><dt>${escape(k)}</dt><dd>${escape(v)}</dd></div>`).join("")}</dl>
    <div class="kc-ws-body kc-ws-body-${w.kind}">${body}</div>
    <div class="kc-ws-foot"><span>${escape(w.foot[0])}</span><strong>${escape(w.foot[1])}</strong><span>${escape(w.foot[2])}</span></div>
  </section>
  <section class="kc-ws-atlas" aria-label="Atlas AI sample preview">
    <div class="kc-ws-atlas-head">${slogan("atlasAI", true)}<span>Demo · sample data</span><button type="button" class="kc-ws-pause" hidden aria-pressed="false" aria-label="Pause workspace animation" title="Pause workspace animation"><svg class="kc-ws-pause-icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true" focusable="false"><path d="M8 5v14M16 5v14" /></svg><svg class="kc-ws-play-icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="m8 5 11 7-11 7Z" /></svg></button></div>
    <div class="kc-ws-response" aria-live="polite" aria-atomic="true">
    <p class="kc-ws-prompt">${escape(act.q)}</p>
    <p class="kc-ws-answer" data-answer="${escape(act.say)}">${escape(act.say)}</p>
    <p class="kc-ws-result">Sample records · ${escape(act.touch.join(" · "))}</p>
    </div>
    <div class="kc-ws-options" role="group" aria-label="Sample questions" hidden>${acts.map((option, index) => `<button type="button" aria-pressed="${index === 0}" data-question="${escape(option.q)}" data-response="${escape(option.say)}" data-records="${escape(option.touch.join(" · "))}">${escape(option.q)}</button>`).join("")}</div>
  </section>
</div>
`;
  }
  return files;
}
