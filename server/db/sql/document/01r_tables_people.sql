CREATE TABLE IF NOT EXISTS document.shift_assignment (
    id uuid NOT NULL DEFAULT shared.uuidv7(),
    tenant_id uuid NOT NULL,
    code text NOT NULL,
    name text NOT NULL DEFAULT '',
    employee_id uuid NOT NULL,
    shift_type_id uuid NOT NULL,
    work_date date NOT NULL,
    planned_start_at timestamptz NOT NULL,
    planned_end_at timestamptz NOT NULL,
    source_type text NOT NULL DEFAULT 'schedule',
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'scheduled',
    is_active boolean GENERATED ALWAYS AS (status IN ('scheduled', 'worked', 'adjusted')) STORED,
    status_changed_at timestamptz,
    status_changed_by uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid NOT NULL,
    updated_at timestamptz,
    updated_by uuid,
    CONSTRAINT shift_assignment_pkey PRIMARY KEY (id),
    CONSTRAINT shift_assignment_tenant_id_uq UNIQUE (tenant_id, id),
    CONSTRAINT shift_assignment_code_uq UNIQUE (tenant_id, code),
    CONSTRAINT shift_assignment_employee_date_uq UNIQUE (tenant_id, employee_id, work_date),
    CONSTRAINT shift_assignment_time_chk CHECK (planned_end_at > planned_start_at),
    CONSTRAINT shift_assignment_date_consistency_chk CHECK (planned_start_at::date = work_date),
    CONSTRAINT shift_assignment_status_chk CHECK (status IN ('scheduled', 'worked', 'adjusted', 'cancelled')),
    CONSTRAINT shift_assignment_employee_fk FOREIGN KEY (tenant_id, employee_id) REFERENCES master.employee (tenant_id, id),
    CONSTRAINT shift_assignment_shift_type_fk FOREIGN KEY (tenant_id, shift_type_id) REFERENCES master.shift_type (tenant_id, id)
);

