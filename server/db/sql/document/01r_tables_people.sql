CREATE TABLE IF NOT EXISTS document.payroll_result (
    id uuid NOT NULL DEFAULT shared.uuidv7(),
    tenant_id uuid NOT NULL,
    payroll_run_id uuid NOT NULL,
    payroll_run_employee_id uuid NOT NULL,
    employee_id uuid NOT NULL,
    currency_code char(3) NOT NULL,
    gross_amount numeric(18,4) NOT NULL DEFAULT 0,
    employee_deduction_amount numeric(18,4) NOT NULL DEFAULT 0,
    employer_contribution_amount numeric(18,4) NOT NULL DEFAULT 0,
    net_amount numeric(18,4) NOT NULL DEFAULT 0,
    calculation_trace jsonb NOT NULL DEFAULT '{}'::jsonb,
    render_output_id uuid,
    status text NOT NULL DEFAULT 'calculated',
    is_active boolean GENERATED ALWAYS AS (status IN ('calculated', 'approved', 'posted')) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid NOT NULL,
    updated_at timestamptz,
    updated_by uuid,
    CONSTRAINT payroll_result_pkey PRIMARY KEY (id),
    CONSTRAINT payroll_result_tenant_id_uq UNIQUE (tenant_id, id),
    CONSTRAINT payroll_result_employee_uq UNIQUE (tenant_id, payroll_run_id, employee_id),
    CONSTRAINT payroll_result_amount_chk CHECK (
        gross_amount >= 0 AND employee_deduction_amount >= 0
        AND employer_contribution_amount >= 0 AND net_amount >= 0
    ),
    CONSTRAINT payroll_result_net_consistency_chk CHECK (
        ABS(net_amount - (gross_amount - employee_deduction_amount)) < 0.005
    ),
    CONSTRAINT payroll_result_currency_chk CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT payroll_result_trace_chk CHECK (jsonb_typeof(calculation_trace) = 'object'),
    CONSTRAINT payroll_result_status_chk CHECK (status IN ('calculated', 'approved', 'posted', 'voided')),
    CONSTRAINT payroll_result_run_fk FOREIGN KEY (tenant_id, payroll_run_id) REFERENCES document.payroll_run (tenant_id, id),
    CONSTRAINT payroll_result_run_employee_fk FOREIGN KEY (tenant_id, payroll_run_employee_id) REFERENCES document.payroll_run_employee (tenant_id, id),
    CONSTRAINT payroll_result_employee_fk FOREIGN KEY (tenant_id, employee_id) REFERENCES master.employee (tenant_id, id),
    CONSTRAINT payroll_result_render_fk FOREIGN KEY (tenant_id, render_output_id) REFERENCES document.render_output (tenant_id, id)
