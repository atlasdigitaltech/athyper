    late_minutes smallint NOT NULL DEFAULT 0,
    early_leave_minutes smallint NOT NULL DEFAULT 0,
    absence_minutes smallint NOT NULL DEFAULT 0,
    first_in_at timestamptz,
    last_out_at timestamptz,
