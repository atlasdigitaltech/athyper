-- master.comment_intent — semantic role of a master.comment row.
-- Orthogonal to context_type. Drives intent badges + filter chips in the
-- Comments panel and is set by entity_flow_field.metadata.target when a
-- flow writes a comment. is_extensible=true (tenants/packs can add codes).

INSERT INTO control.lookup_value
    (code, name, domain_code, description, sort_order, metadata,
     is_system, status, created_by)
SELECT v.code, v.name, v.domain_code, v.description, v.sort_order, v.metadata::jsonb,
       true, 'active', '00000000-0000-0000-0000-000000000000'
FROM (VALUES
    ('general',           'General',
     'master.comment_intent',
     'Free-form discussion. Default when no specific role applies.',
     10,
     '{"icon":"message_square","tone":"muted"}'),

    ('submission_note',   'Submission Note',
     'master.comment_intent',
     'Note left by the submitter when routing a document into an approval '
     'workflow. Captured by the submit-for-approval flow.',
     20,
     '{"icon":"send","tone":"info"}'),

    ('approval_note',     'Approval Note',
     'master.comment_intent',
     'Note left by an approver when approving a workflow stage.',
     30,
     '{"icon":"check_circle","tone":"success"}'),

    ('rejection_reason',  'Rejection Reason',
     'master.comment_intent',
     'Required note left by an approver when rejecting or returning a '
     'workflow stage. Treated as audit evidence.',
     40,
     '{"icon":"x_circle","tone":"danger"}'),

    ('query',             'Query',
     'master.comment_intent',
     'Question raised against the document or one of its lines, awaiting a '
     'clarification response.',
     50,
     '{"icon":"help_circle","tone":"warning"}'),

    ('clarification',     'Clarification',
     'master.comment_intent',
     'Response to a query. Typically a reply within the same thread.',
     60,
     '{"icon":"message_circle","tone":"info"}'),

    ('audit_note',        'Audit Note',
     'master.comment_intent',
     'Annotation left by an auditor or compliance reviewer. Subject to '
     'legal-hold + retention policies.',
     70,
     '{"icon":"shield_check","tone":"muted"}'),

    ('system_event',      'System Event',
     'master.comment_intent',
     'Machine-authored note generated by an automation (workflow engine, '
     'integration, scheduled job). Not user-editable.',
     80,
     '{"icon":"cpu","tone":"muted"}')
) AS v(code, name, domain_code, description, sort_order, metadata)
WHERE NOT EXISTS (
    SELECT 1 FROM control.lookup_value x
    WHERE x.domain_code = v.domain_code AND x.code = v.code AND x.tenant_id IS NULL
);
