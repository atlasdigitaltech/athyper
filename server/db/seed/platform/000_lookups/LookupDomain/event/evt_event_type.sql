-- Event types per Engine spec 4.13.

INSERT INTO control.lookup_value
    (code, name, domain_code, description, sort_order, is_system, status, created_by)
SELECT v.code, v.name, v.domain_code, v.description, v.sort_order,
       true, 'active', '00000000-0000-0000-0000-000000000000'
FROM (VALUES
    ('intent.resolved',    'Intent Resolved',          'evt.event_type', 'Business intent successfully resolved by control.resolve_business_intent().',                  10),
    ('profile.resolved',   'Profile Resolved',         'evt.event_type', 'Accounting profile successfully resolved by control.resolve_accounting_profile().',            20),
    ('entry.generated',    'JE Entries Expanded',      'evt.event_type', 'Journal entry lines generated by control.generate_event_entries().',                           30),
    ('obligation.planned', 'Obligation Created',       'evt.event_type', 'Obligation horizon row created in PLANNED tier by the resolution engine.',                     40),
    ('obligation.promoted','Obligation Tier Advanced', 'evt.event_type', 'Obligation promoted from PLANNED → FORECAST or FORECAST → RESERVED by promote_obligation_tier().', 50),
    ('revenue.recognized', 'Revenue Recognised',       'evt.event_type', 'Revenue recognition entry generated upon obligation_satisfied or period_recognition event.',   60),
    ('cogs.matched',       'COGS Paired to Revenue',   'evt.event_type', 'Symmetric COGS entry generated as paired counterpart to a revenue recognition entry.',         70),
    ('settlement.arranged','Payment Arranged',         'evt.event_type', 'Settlement or payment entry generated following a settlement event code.',                     80)
) AS v(code, name, domain_code, description, sort_order)
WHERE NOT EXISTS (
    SELECT 1 FROM control.lookup_value x
    WHERE x.domain_code = v.domain_code AND x.code = v.code AND x.tenant_id IS NULL
);
